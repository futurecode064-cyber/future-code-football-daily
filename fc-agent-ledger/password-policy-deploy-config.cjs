const fs=require('node:fs');
const cp=require('node:child_process');
const dbs=JSON.parse(cp.execFileSync('npx',['wrangler','d1','list','--json'],{encoding:'utf8'}));
const db=dbs.find(x=>x.name==='fc-agent-ledger-private-v1-db');
if(!db?.uuid&&!db?.id)throw Error('Dedicated FC ledger D1 database not found; no deployment');
const release=fs.readFileSync('../../../.github/workflows/fc-agent-ledger-release.yml','utf8');
const setupHash=release.match(/SETUP_TOKEN_SHA256:'([a-f0-9]{64})'/)?.[1];
if(!setupHash)throw Error('Cannot preserve existing bootstrap hash; no deployment');
const cfg=JSON.parse(fs.readFileSync('wrangler.jsonc','utf8'));
cfg.name='fc-agent-ledger-private-v1';
cfg.d1_databases[0].database_name=db.name;
cfg.d1_databases[0].database_id=db.uuid||db.id;
cfg.vars={SETUP_TOKEN_SHA256:setupHash};
fs.writeFileSync('wrangler.jsonc',JSON.stringify(cfg,null,2)+'\n');
let src=fs.readFileSync('src/worker.mjs','utf8');
const oldStatus="enabled:typeof env.SETUP_TOKEN==='string'&&env.SETUP_TOKEN.length>=32";
const newStatus="enabled:typeof env.SETUP_TOKEN_SHA256==='string'&&env.SETUP_TOKEN_SHA256.length===64";
const oldCheck="if(typeof env.SETUP_TOKEN!=='string'||env.SETUP_TOKEN.length<32||d.setupToken!==env.SETUP_TOKEN)fail(403,'Setup disabled or token invalid');";
const newCheck="if(typeof d.setupToken!=='string'||typeof env.SETUP_TOKEN_SHA256!=='string'||await hashSha(d.setupToken)!==env.SETUP_TOKEN_SHA256)fail(403,'Setup disabled or token invalid');";
if(!src.includes(oldStatus)||!src.includes(oldCheck))throw Error('Setup markers changed; no deployment');
src=src.replace(oldStatus,newStatus).replace(oldCheck,newCheck);
fs.writeFileSync('src/worker.mjs',src);
console.log('Reusing FC Agent Ledger Worker, D1, and setup hash without creating resources');
